def build_artifact_tokens() -> None:
    """tokens.json for the browsable Design System artifact.

    Hex rather than oklch: the page accepts both, hex is unambiguous for alpha,
    and these hexes are exact equivalents of the oklch the web output ships.
    """
    colors = [{
        "name": n,
        "value": {
            m: (RESOLVED[n][m]["hex8"] if RESOLVED[n][m]["alpha"] < 1
                else RESOLVED[n][m]["hex"]).lower()
            for m in MODES
        },
        "usage": COLOR_USAGE[n],
    } for n in NAMES]

    groups = {}
    for name, s in STYLES.items():
        groups.setdefault(s["family"], []).append({
            "name": name,
            "fontSize": s["fontSize"],
            "lineHeight": s["lineHeight"],
            "fontWeight": s["fontWeight"],
            "usage": s["usage"],
            **({"sample": "0123456789  $1,842.10"} if s.get("tabular") else {}),
        })

    out = {
        "name": META["name"],
        "version": 2,
        "meta": {"source": META["source"], "extracted": META["extracted"]},
        "color": {
            "themes": [{"id": "light", "name": "Light"}, {"id": "dark", "name": "Dark"}],
            "tokens": colors,
        },
        "type": {
            "fonts": [],
            "families": {k: v["stack"] for k, v in FAMILIES.items()},
            "groups": [
                {"name": "Sans (Roboto)", "family": "sans", "styles": groups["sans"]},
                {"name": "Mono (Geist Mono)", "family": "mono", "styles": groups["mono"]},
            ],
        },
        # Prefixed: the artifact page derives CSS custom-property names straight
        # from token names, and every family but type shares one namespace. Bare
        # "sm"/"md"/"lg" would both read wrong as --sm and collide with spacing
        # when that family lands.
        "radius": {
            "note": RADIUS["meta"]["note"],
            "tokens": [{"name": f"radius-{k}", "value": v["value"], "usage": v["usage"]}
                       for k, v in RADII.items()],
        },
        "size": {
            "note": SIZE["meta"]["note"],
            "tokens": [{"name": f"size-{k}", "value": v["value"], "usage": v["usage"]}
                       for k, v in SIZES.items()],
            "roles": [{"name": f"control-{k}", "value": SIZES[v["ref"]]["value"], "usage": v["usage"]}
                      for k, v in ROLES.items()],
        },
        "spacing": {
            "note": SPACING["meta"]["note"],
            "tokens": [{"name": f"space-{k}", "value": v["value"], "usage": v["usage"]}
                       for k, v in SPACE.items()],
        },
        "shadow": {
            "note": ELEVATION["meta"]["note"],
            "tokens": [{"name": f"shadow-{k}", "value": v["value"], "usage": v["usage"]}
                       for k, v in ELEV.items()],
        },
    }
    write(DIST / "artifact" / "tokens.json", json.dumps(out, indent=2) + "\n")


