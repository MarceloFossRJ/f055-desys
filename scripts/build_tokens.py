#!/usr/bin/env python3
"""
Generate every platform output from tokens/*.json.

    python3 scripts/build_tokens.py

Hand-edit only tokens/color.json, tokens/typography.json and tokens/radius.json.
Never edit anything under dist/ -- the next build overwrites it.
"""
from __future__ import annotations

import datetime
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIST = ROOT / "dist"
MODES = ("light", "dark")

COLOR = json.loads((ROOT / "tokens" / "color.json").read_text())
TYPE = json.loads((ROOT / "tokens" / "typography.json").read_text())
RADIUS = json.loads((ROOT / "tokens" / "radius.json").read_text())
SPACING = json.loads((ROOT / "tokens" / "spacing.json").read_text())
ELEVATION = json.loads((ROOT / "tokens" / "elevation.json").read_text())
SIZE = json.loads((ROOT / "tokens" / "size.json").read_text())

PALETTE, SEMANTIC, META = COLOR["palette"], COLOR["semantic"], COLOR["meta"]
FAMILIES = TYPE["families"]
SCALE = {k: v for k, v in TYPE["scale"].items() if not k.startswith("$")}
STYLES = TYPE["styles"]
RADII = RADIUS["tokens"]
SPACE = SPACING["tokens"]
ELEV = ELEVATION["tokens"]
SIZES = SIZE["tokens"]
ROLES = SIZE["roles"]

BANNER = (
    "Generated by scripts/build_tokens.py from tokens/*.json -- do not edit by hand.\n"
    f"Design system: {META['name']} v{META['version']} | source: {META['source']}"
)


# ---------------------------------------------------------------- resolution

def _rgba(hex6: str, alpha: float) -> str:
    r, g, b = (int(hex6[i:i + 2], 16) for i in (1, 3, 5))
    return f"rgba({r}, {g}, {b}, {alpha:g})"


def resolve(spec: dict) -> dict:
    base = PALETTE[spec["ref"]]
    alpha = spec.get("alpha")
    hex6, oklch = base["hex"].upper(), base["oklch"]
    if alpha is None:
        return {"ref": spec["ref"], "alpha": 1.0, "hex": hex6, "hex8": hex6 + "FF",
                "oklch": oklch, "rgba": _rgba(hex6, 1.0), "css": oklch}
    return {"ref": spec["ref"], "alpha": alpha, "hex": hex6,
            "hex8": hex6 + format(round(alpha * 255), "02X"), "oklch": oklch,
            "rgba": _rgba(hex6, alpha),
            "css": oklch.rstrip(")") + f" / {round(alpha * 100)}%)"}


RESOLVED = {n: {m: resolve(t[m]) for m in MODES} for n, t in SEMANTIC.items()}
NAMES = list(RESOLVED)


def camel(name: str) -> str:
    head, *rest = name.replace(".", "-").split("-")
    return head + "".join(p.capitalize() for p in rest)


def kid(name: str) -> str:
    """A Kotlin/Swift-safe identifier (scale keys like '2xl' start with a digit)."""
    c = camel(name)
    return ("s" + c) if c[0].isdigit() else c


def px(v: str) -> float:
    return float(str(v).replace("px", ""))


def write(path: pathlib.Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print(f"  wrote {path.relative_to(ROOT)}")


# --------------------------------------------------------------- web/tailwind

def build_web_css() -> None:
    def colors(mode: str) -> str:
        return "\n".join(f"  --{n}: {RESOLVED[n][mode]['css']};" for n in NAMES)

    fonts = "\n".join(f"  --font-{k}: {v['stack']};" for k, v in FAMILIES.items())
    radii = "\n".join(f"  --radius-{k}: {v['value']};" for k, v in RADII.items())
    spaces = "\n".join(f"  --space-{k}: {v['value']};" for k, v in SPACE.items())
    sizes = "\n".join(f"  --size-{k}: {v['value']};" for k, v in SIZES.items())
    roles = "\n".join(f"  --control-{k}: var(--size-{v['ref']});" for k, v in ROLES.items())

    def shadows(mode: str) -> str:
        return "\n".join(f"  --elevation-{k}: {v['value'][mode]};" for k, v in ELEV.items())

    # Mapped through a differently-named custom property so the `shadow-*`
    # utilities follow .dark; a self-referential --shadow-x: var(--shadow-x)
    # would not resolve.
    theme_shadows = "\n".join(
        f"  --shadow-{k}: var(--elevation-{k});" for k in ELEV)

    # The same aliases in :root, so `var(--shadow-card)` resolves in plain CSS
    # too. Without these the component previews render flat wherever Tailwind is
    # not in the pipeline -- opened straight from disk, or in a screenshot job --
    # because @theme is a Tailwind construct, not a cascade layer.
    root_shadows = theme_shadows
    text = "\n".join(
        f"  --text-{k}: {v['fontSize']};\n  --text-{k}--line-height: {v['lineHeight']};"
        for k, v in SCALE.items()
    )
    theme_colors = "\n".join(f"  --color-{n}: var(--{n});" for n in NAMES)

    def style_rule(name: str, s: dict) -> str:
        decls = [
            f"  font-family: var(--font-{s['family']});",
            f"  font-size: {s['fontSize']};",
            f"  line-height: {s['lineHeight']};",
            f"  font-weight: {s['fontWeight']};",
        ]
        if s.get("textTransform"):
            decls.append(f"  text-transform: {s['textTransform']};")
        if s.get("tabular"):
            decls.append("  font-variant-numeric: tabular-nums;")
        return f".type-{name} {{\n" + "\n".join(decls) + "\n}"

    styles = "\n\n".join(style_rule(n, s) for n, s in STYLES.items())

    css = f"""/*
 * {BANNER.splitlines()[0]}
 * {BANNER.splitlines()[1]}
 *
 * Tailwind v4. Import after `@import "tailwindcss";`.
 *
 * Colour       -> bg-background, text-muted-foreground, border-border, fill-chart-1
 * Family       -> font-sans, font-mono
 * Size         -> text-xs … text-3xl (these match Tailwind's own defaults; declared
 *                 here so the values are explicit and shared with the other stacks)
 * Radius       -> rounded-5, rounded-6, rounded-8, rounded-10, rounded-14,
 *                 rounded-pill, rounded-24, rounded-full. Tailwind's own radius
 *                 scale is cleared, so rounded-xl and friends produce nothing.
 * Elevation    -> shadow-card, shadow-raised, shadow-thumb, shadow-none
 * Spacing      -> p-5, gap-1.5 … Tailwind's default scale already produces every
 *                 step the reference uses, so nothing is overridden; --space-* is
 *                 declared for hand-written CSS and for parity with the other stacks
 * Size         -> --size-4 … --size-64 (control heights, icon boxes, indicators) and
 *                 --control-<role>, which says what a size is FOR. These are NOT in
 *                 @theme: Tailwind has no --size-* namespace, and routing them through
 *                 --spacing-* would silently redefine p-32 from 128px to 32px. In
 *                 Tailwind use the custom-property form -- h-(--control-button),
 *                 size-(--control-icon) -- or var() in hand-written CSS.
 * Data colour  -> chart-1..5 is a SEQUENTIAL ramp; the dark ramp is the light one
 *                 reversed, so step 1 is always nearest the surface. series-1..3 is
 *                 the CATEGORICAL set; assign in order, never cycle, and give series-3
 *                 a distinct mark type because it equals muted-foreground.
 * Named styles -> class="type-label", class="type-display" (see the end of this file)
 *
 * Dark mode is driven by the `.dark` class.
 */

@custom-variant dark (&:where(.dark, .dark *));

:root {{
{colors("light")}

{fonts}

{radii}

{spaces}

{sizes}

{roles}

{shadows("light")}

{root_shadows}
}}

.dark {{
{colors("dark")}

{shadows("dark")}
}}

@theme inline {{
  /* Clear Tailwind's own radius, shadow and text scales before declaring ours.
     Without this they coexist: `rounded-xl` silently resolves to Tailwind's
     12px, which is not an F055 radius at all, and nothing flags it. Cleared,
     an off-system utility produces no CSS -- a loud failure instead of a
     plausible wrong value. */
  --radius-*: initial;
  --shadow-*: initial;
  --text-*: initial;

{theme_colors}

{fonts}

{text}

{radii}

{theme_shadows}
}}

/*
 * Named type styles.
 *
 * Tailwind utilities cover family, size and weight individually; these classes
 * bundle the combinations the reference actually uses, which is what you want in
 * a Jinja2 or ERB template where repeating four utilities on every label is
 * noise. In React, compose the utilities or wrap these in a component -- either
 * is fine, but pick one per project.
 */

{styles}
"""
    write(DIST / "web" / "tokens.css", css)


def build_web_js() -> None:
    def obj(mode: str) -> str:
        rows = ",\n".join(
            f'    "{n}": "{RESOLVED[n][mode]["hex8" if RESOLVED[n][mode]["alpha"] < 1 else "hex"]}"'
            for n in NAMES)
        return "{\n" + rows + "\n  }"

    fam = ",\n".join(f'    {k}: {json.dumps(v["stack"])}' for k, v in FAMILIES.items())
    rad = ",\n".join(f'    "{k}": "{v["value"]}"' for k, v in RADII.items())
    spc = ",\n".join(f'    "{k}": "{v["value"]}"' for k, v in SPACE.items())
    siz = ",\n".join(f'    "{k}": "{v["value"]}"' for k, v in SIZES.items())
    rol = ",\n".join(f'    "{k}": "{SIZES[v["ref"]]["value"]}"' for k, v in ROLES.items())
    shd = ",\n".join(f'    "{k}": "{v["value"]["light"]}"' for k, v in ELEV.items())
    fs = ",\n".join(f'    "{k}": ["{v["fontSize"]}", {{ lineHeight: "{v["lineHeight"]}" }}]'
                    for k, v in SCALE.items())

    js = f"""// {BANNER.splitlines()[0]}
// {BANNER.splitlines()[1]}
//
// Tailwind v3: spread into theme.extend. Tailwind v4 projects import
// dist/web/tokens.css instead.

export const colors = {{
  light: {obj("light")},
  dark: {obj("dark")},
}};

export const fontFamily = {{
{fam}
}};

export const fontSize = {{
{fs}
}};

export const borderRadius = {{
{rad}
}};

export const spacing = {{
{spc}
}};

export const size = {{
{siz}
}};

/** What each size is FOR. `control.button` is 32px, so a button never has to be remembered as a number. */
export const control = {{
{rol}
}};

// Light-mode values. `card` differs in dark (its ring flips to near-white at
// 10%); drive that with a dark: variant or the v4 stylesheet.
export const boxShadow = {{
{shd}
}};

export default {{ colors, fontFamily, fontSize, borderRadius, spacing, boxShadow }};
"""
    write(DIST / "web" / "tokens.js", js)


# -------------------------------------------------------------------- python

def build_python() -> None:
    def centries(mode: str) -> str:
        return "\n".join(
            f'    "{n}": Color(hex="{RESOLVED[n][mode]["hex"]}", hex8="{RESOLVED[n][mode]["hex8"]}", '
            f'rgba="{RESOLVED[n][mode]["rgba"]}", css="{RESOLVED[n][mode]["css"]}"),'
            for n in NAMES)

    styles = "\n".join(
        f'    "{n}": TextStyle(family={json.dumps(FAMILIES[s["family"]]["stack"])}, '
        f'font_size="{s["fontSize"]}", line_height="{s["lineHeight"]}", '
        f'font_weight={s["fontWeight"]}, '
        f'text_transform={repr(s.get("textTransform"))}, '
        f'tabular={bool(s.get("tabular"))}),'
        for n, s in STYLES.items())

    radii = "\n".join(f'    "{k}": "{v["value"]}",' for k, v in RADII.items())
    spaces = "\n".join(f'    "{k}": "{v["value"]}",' for k, v in SPACE.items())
    sizes = "\n".join(f'    "{k}": "{v["value"]}",' for k, v in SIZES.items())
    roles = "\n".join(f'    "{k}": "{SIZES[v["ref"]]["value"]}",' for k, v in ROLES.items())
    shadows = "\n".join(
        f'    "{k}": Shadow(light="{v["value"]["light"]}", dark="{v["value"]["dark"]}"),'
        for k, v in ELEV.items())

    py = f'''"""
{BANNER}

FastAPI + Jinja2. Register once:

    from design_system.tokens import jinja_globals
    templates.env.globals.update(jinja_globals())

then in a template:

    <meta name="theme-color" content="{{{{ colors.light.background.hex }}}}">
    <span style="{{{{ type.label.css }}}}">Email</span>

Most styling should go through Tailwind classes backed by dist/web/tokens.css.
Reach for this module when a value must exist server-side: emails, SVG and chart
generation, PDF export, or a theme-color meta tag.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, Optional


@dataclass(frozen=True)
class Color:
    hex: str      # "#RRGGBB" -- alpha dropped, for contexts that cannot express it
    hex8: str     # "#RRGGBBAA"
    rgba: str     # "rgba(r, g, b, a)"
    css: str      # oklch(), the authoritative web form

    def __str__(self) -> str:
        return self.css


@dataclass(frozen=True)
class Shadow:
    light: str
    dark: str

    def for_mode(self, mode: str = "light") -> str:
        return self.dark if mode == "dark" else self.light

    def __str__(self) -> str:
        return self.light


@dataclass(frozen=True)
class TextStyle:
    family: str
    font_size: str
    line_height: str
    font_weight: int
    text_transform: Optional[str] = None
    tabular: bool = False

    @property
    def css(self) -> str:
        """An inline style declaration, for mail and PDF where classes do not apply."""
        parts = [
            f"font-family: {{self.family}}",
            f"font-size: {{self.font_size}}",
            f"line-height: {{self.line_height}}",
            f"font-weight: {{self.font_weight}}",
        ]
        if self.text_transform:
            parts.append(f"text-transform: {{self.text_transform}}")
        if self.tabular:
            parts.append("font-variant-numeric: tabular-nums")
        return "; ".join(parts) + ";"

    def __str__(self) -> str:
        return self.css


LIGHT: Dict[str, Color] = {{
{centries("light")}
}}

DARK: Dict[str, Color] = {{
{centries("dark")}
}}

SCHEMES: Dict[str, Dict[str, Color]] = {{"light": LIGHT, "dark": DARK}}

TYPE: Dict[str, TextStyle] = {{
{styles}
}}

RADIUS: Dict[str, str] = {{
{radii}
}}

SPACING: Dict[str, str] = {{
{spaces}
}}

SIZE: Dict[str, str] = {{
{sizes}
}}

#: What each size is FOR: CONTROL["button"] == "32px".
CONTROL: Dict[str, str] = {{
{roles}
}}

ELEVATION: Dict[str, "Shadow"] = {{
{shadows}
}}


def scheme(mode: str = "light") -> Dict[str, Color]:
    """Look up a whole colour scheme, defaulting to light for unknown input."""
    return SCHEMES.get(mode, LIGHT)


def jinja_globals() -> dict:
    """Globals to merge into a Jinja2 environment."""

    class _Ns(dict):
        __getattr__ = dict.__getitem__

    return {{
        "colors": _Ns(light=_Ns(LIGHT), dark=_Ns(DARK)),
        "color_scheme": scheme,
        "type": _Ns(TYPE),
        "radius": _Ns(RADIUS),
        "space": _Ns(SPACING),
        "elevation": _Ns(ELEVATION),
    }}
'''
    write(DIST / "python" / "tokens.py", py)


# ---------------------------------------------------------------------- ruby

def build_ruby() -> None:
    def centries(mode: str) -> str:
        return "\n".join(
            f'      {n.replace("-", "_")}: Color.new("{RESOLVED[n][mode]["hex"]}", '
            f'"{RESOLVED[n][mode]["hex8"]}", "{RESOLVED[n][mode]["rgba"]}", '
            f'"{RESOLVED[n][mode]["css"]}").freeze,'
            for n in NAMES)

    styles = "\n".join(
        f'      {n.replace("-", "_")}: TextStyle.new({json.dumps(FAMILIES[s["family"]]["stack"])}, '
        f'"{s["fontSize"]}", "{s["lineHeight"]}", {s["fontWeight"]}, '
        f'{json.dumps(s.get("textTransform")) if s.get("textTransform") else "nil"}, '
        f'{str(bool(s.get("tabular"))).lower()}).freeze,'
        for n, s in STYLES.items())

    # `=>` with string keys, for both reasons: `"20": x` defines the SYMBOL :"20"
    # rather than a string key, and a BARE `5: x` is not valid Ruby at all. The
    # radius hash used the bare form, so this file never parsed until 2026-10-24.
    radii = "\n".join(f'      "{k}" => "{v["value"]}",' for k, v in RADII.items())
    spaces = "\n".join(
        f'      "{k}" => "{v["value"]}",' for k, v in SPACE.items())
    sizes = "\n".join(
        f'      "{k}" => "{v["value"]}",' for k, v in SIZES.items())
    roles = "\n".join(
        f'      "{k}" => "{SIZES[v["ref"]]["value"]}",' for k, v in ROLES.items())
    shadows = "\n".join(
        f'      {k}: Shadow.new("{v["value"]["light"]}", "{v["value"]["dark"]}").freeze,'
        for k, v in ELEV.items())

    rb = f"""# frozen_string_literal: true

# {BANNER.splitlines()[0]}
# {BANNER.splitlines()[1]}
#
# Rails. Views should style through Tailwind classes backed by
# dist/web/tokens.css. Use this module when a value must exist in Ruby:
# ActionMailer templates, generated SVG or charts, PDF export, a theme-color tag.
#
#   F055::Tokens.scheme(:dark)[:background].hex  # => "{RESOLVED['background']['dark']['hex']}"
#   F055::Tokens::TYPE[:label].css
#   F055::Tokens::RADIUS["pill"]                 # => "{RADII["pill"]["value"]}"

module F055
  module Tokens
    Color = Struct.new(:hex, :hex8, :rgba, :css) do
      def to_s = css
    end

    Shadow = Struct.new(:light, :dark) do
      def for_mode(mode = :light) = mode.to_sym == :dark ? dark : light
      def to_s = light
    end

    TextStyle = Struct.new(:family, :font_size, :line_height, :font_weight,
                           :text_transform, :tabular) do
      # An inline style declaration, for mail and PDF where classes do not apply.
      def css
        parts = ["font-family: #{{family}}", "font-size: #{{font_size}}",
                 "line-height: #{{line_height}}", "font-weight: #{{font_weight}}"]
        parts << "text-transform: #{{text_transform}}" if text_transform
        parts << "font-variant-numeric: tabular-nums" if tabular
        "#{{parts.join('; ')}};"
      end

      def to_s = css
    end

    LIGHT = {{
{centries("light")}
    }}.freeze

    DARK = {{
{centries("dark")}
    }}.freeze

    SCHEMES = {{ light: LIGHT, dark: DARK }}.freeze

    TYPE = {{
{styles}
    }}.freeze

    RADIUS = {{
{radii}
    }}.freeze

    # String keys: the scale uses Tailwind step names, several of which are
    # fractional ("0.5", "1.5") and are not valid Ruby symbols.
    SPACING = {{
{spaces}
    }}.freeze

    # String keys for the same reason SPACING uses them: "16" is not a Ruby symbol.
    SIZE = {{
{sizes}
    }}.freeze

    # What each size is FOR: CONTROL["button"] => "32px".
    CONTROL = {{
{roles}
    }}.freeze

    ELEVATION = {{
{shadows}
    }}.freeze

    # Unknown names fall back to light rather than raising, so a bad param
    # cannot take a page down.
    def self.scheme(mode = :light)
      SCHEMES.fetch(mode.to_sym, LIGHT)
    end
  end
end
"""
    write(DIST / "ruby" / "f055_tokens.rb", rb)


