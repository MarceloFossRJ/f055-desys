def build_kotlin_colors() -> None:
    def kc(c: dict) -> str:
        return f"Color(0x{c['hex8'][7:9]}{c['hex8'][1:7]})"

    def vals(mode: str) -> str:
        return "\n".join(f"    val {camel(n)}: Color = {kc(RESOLVED[n][mode])}" for n in NAMES)

    iface = "\n".join(f"    val {camel(n)}: Color" for n in NAMES)

    kt = f"""// {BANNER.splitlines()[0]}
// {BANNER.splitlines()[1]}
//
// Compose Multiplatform: Android, iOS and web (Wasm/JS) from one source.
// Wrap the app in F055Theme and read semantic colours from LocalF055Colors;
// MaterialTheme.colorScheme is wired for Material 3 components.

package design.f055.tokens

import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.runtime.Composable
import androidx.compose.runtime.CompositionLocalProvider
import androidx.compose.runtime.Immutable
import androidx.compose.runtime.staticCompositionLocalOf
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.font.FontFamily

@Immutable
interface F055Colors {{
{iface}
}}

object F055Light : F055Colors {{
{vals("light")}
}}

object F055Dark : F055Colors {{
{vals("dark")}
}}

val LocalF055Colors = staticCompositionLocalOf<F055Colors> {{ F055Light }}

/**
 * Material 3 mapping. The semantic set is richer than Material's slots, so
 * `muted` and the chart ramp stay available only through LocalF055Colors.
 */
private fun materialLight() = lightColorScheme(
    primary = F055Light.primary,
    onPrimary = F055Light.primaryForeground,
    secondary = F055Light.secondary,
    onSecondary = F055Light.secondaryForeground,
    background = F055Light.background,
    onBackground = F055Light.foreground,
    surface = F055Light.card,
    onSurface = F055Light.cardForeground,
    surfaceVariant = F055Light.muted,
    onSurfaceVariant = F055Light.mutedForeground,
    outline = F055Light.border,
    error = F055Light.destructive,
    onError = F055Light.destructiveForeground,
)

private fun materialDark() = darkColorScheme(
    primary = F055Dark.primary,
    onPrimary = F055Dark.primaryForeground,
    secondary = F055Dark.secondary,
    onSecondary = F055Dark.secondaryForeground,
    background = F055Dark.background,
    onBackground = F055Dark.foreground,
    surface = F055Dark.card,
    onSurface = F055Dark.cardForeground,
    surfaceVariant = F055Dark.muted,
    onSurfaceVariant = F055Dark.mutedForeground,
    outline = F055Dark.border,
    error = F055Dark.destructive,
    onError = F055Dark.destructiveForeground,
)

/**
 * @param sans Roboto, loaded per platform (Android: res/font; iOS and web: a
 *   bundled resource). Falls back to FontFamily.Default if you pass nothing,
 *   which is a visible downgrade -- bundle the real face.
 * @param mono Geist Mono, same.
 */
@Composable
fun F055Theme(
    dark: Boolean,
    sans: FontFamily = FontFamily.Default,
    mono: FontFamily = FontFamily.Monospace,
    content: @Composable () -> Unit,
) {{
    val colors = if (dark) F055Dark else F055Light
    val type = f055Type(sans, mono)
    CompositionLocalProvider(
        LocalF055Colors provides colors,
        LocalF055Type provides type,
    ) {{
        MaterialTheme(
            colorScheme = if (dark) materialDark() else materialLight(),
            typography = type.toMaterial(),
            shapes = F055Shapes,
            content = content,
        )
    }}
}}
"""
    write(DIST / "kotlin" / "F055Colors.kt", kt)


def build_kotlin_type() -> None:
    def style(name: str, s: dict) -> str:
        fam = "sans" if s["family"] == "sans" else "mono"
        feat = '\n        fontFeatureSettings = "tnum",' if s.get("tabular") else ""
        return f"""    val {camel(name)}: TextStyle = TextStyle(
        fontFamily = {fam},
        fontSize = {px(s['fontSize']):g}.sp,
        lineHeight = {px(s['lineHeight']):g}.sp,
        fontWeight = FontWeight({s['fontWeight']}),{feat}
    )"""

    iface = "\n".join(f"    val {camel(n)}: TextStyle" for n in STYLES)
    impl = "\n\n".join(style(n, s) for n, s in STYLES.items())
    upper = [n for n, s in STYLES.items() if s.get("textTransform") == "uppercase"]
    upper_note = (
        "\n * Uppercase styles (" + ", ".join(upper) + ") carry no textTransform:\n"
        " * Compose has no such property, so uppercase the string at the call site\n"
        " * with .uppercase() -- and use a locale-aware form where it matters."
    ) if upper else ""

