"""Copy the Latin font files out of node_modules and write a matching stylesheet.

tokens.css names the families and cannot load them -- the gap is documented in
both READMEs. The Next.js example bridges it by importing @fontsource CSS
through a bundler. A Python app has no bundler, so the files are copied into
static/ and the @font-face rules are written here.
"""
import pathlib, shutil

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "static" / "fonts"
OUT.mkdir(parents=True, exist_ok=True)

FACES = [("roboto", "Roboto", [400, 500, 600]), ("geist-mono", "Geist Mono", [400, 500])]

rules, copied = [], 0
for pkg, family, weights in FACES:
    files = HERE / "node_modules" / "@fontsource" / pkg / "files"
    for w in weights:
        src = files / f"{pkg}-latin-{w}-normal.woff2"
        if not src.exists():
            raise SystemExit(f"missing {src} -- run `npm install` first")
        shutil.copy2(src, OUT / src.name); copied += 1
        rules.append(
            f"@font-face {{\n  font-family: '{family}';\n  font-style: normal;\n"
            f"  font-weight: {w};\n  font-display: swap;\n"
            f"  src: url('/static/fonts/{src.name}') format('woff2');\n}}")

(HERE / "static" / "css" / "fonts.css").write_text(
    "/* Generated by build_fonts.py -- do not edit. */\n\n" + "\n\n".join(rules) + "\n")
print(f"{copied} font files -> static/fonts/, {len(rules)} @font-face rules")
