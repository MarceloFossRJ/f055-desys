#!/usr/bin/env ruby
# frozen_string_literal: true

# tokens.css names the font families and cannot load them. Rails has no bundler
# for this, so the Latin subsets are copied into public/assets and the
# @font-face rules written beside them.
require "fileutils"

HERE = __dir__
OUT  = File.join(HERE, "public", "assets", "fonts")
FileUtils.mkdir_p(OUT)

FACES = [["roboto", "Roboto", [400, 500, 600]], ["geist-mono", "Geist Mono", [400, 500]]]

rules = []
FACES.each do |pkg, family, weights|
  weights.each do |w|
    src = File.join(HERE, "node_modules", "@fontsource", pkg, "files",
                    "#{pkg}-latin-#{w}-normal.woff2")
    abort "missing #{src} -- run `npm install` first" unless File.exist?(src)
    FileUtils.cp(src, OUT)
    rules << <<~CSS.strip
      @font-face {
        font-family: '#{family}';
        font-style: normal;
        font-weight: #{w};
        font-display: swap;
        src: url('/assets/fonts/#{File.basename(src)}') format('woff2');
      }
    CSS
  end
end

File.write(File.join(HERE, "public", "assets", "fonts.css"),
           "/* Generated by build_fonts.rb -- do not edit. */\n\n" + rules.join("\n\n") + "\n")
puts "#{rules.size} font files -> public/assets/fonts/, #{rules.size} @font-face rules"
